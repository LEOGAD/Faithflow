// EXPORT CSV
function toCSV(arr) {
  if (!arr.length) return '';
  const keys = Object.keys(arr[0]).filter(k => k !== 'id');
  const header = keys.join(',');
  const rows = arr.map(item => keys.map(k => `"${item[k] ?? ''}"`).join(','));
  return [header, ...rows].join('\n');
}

exports.exportCSV = async (req, res) => {
  try {
    const { collection } = req.params;
    const allowed = ['income', 'expenses', 'attendance', 'members'];
    if (!allowed.includes(collection)) return res.status(400).json({ error: 'Invalid collection' });
    
    // Using flat collection for legacy data or scoped by churchId?
    // We'll query flat 'income' for now as other controllers haven't been updated yet.
    const snap = await db.collection(collection).get();
    const data = snap.docs.map(d => ({ id: d.id, ...d.data() }));
    
    const csv = toCSV(data);
    res.setHeader('Content-Type', 'text/csv');
    res.setHeader('Content-Disposition', `attachment; filename="${collection}_export.csv"`);
    res.send(csv);
  } catch (e) { res.status(500).json({ error: 'Export failed' }); }
};

