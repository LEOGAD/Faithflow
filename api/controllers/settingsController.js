// CREATE USER
exports.createUser = async (req, res) => {
  try {
    const churchId = getChurchId(req);
    const { name, email, password, role } = req.body;
    
    if (!name || !email || !password) return res.status(400).json({ error: 'Missing fields' });
    
    // Check if email exists
    const existing = await db.collection('users').where('email', '==', email.toLowerCase()).get();
    if (!existing.empty) return res.status(400).json({ error: 'User with this email already exists' });
    
    const bcrypt = require('bcryptjs');
    const salt = await bcrypt.genSalt(10);
    const hashedPassword = await bcrypt.hash(password, salt);
    
    const docRef = await db.collection('users').add({
      name,
      email: email.toLowerCase(),
      password: hashedPassword,
      role: role || 'user',
      churchId,
      isVerified: true, // Auto-verified since admin created them
      created_at: new Date().toISOString()
    });
    
    res.status(201).json({ message: 'User created successfully', id: docRef.id });
  } catch (e) { 
    res.status(500).json({ error: 'Failed to create user' }); 
  }
};

