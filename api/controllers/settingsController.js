// Helper to check and seed defaults
async function seedDefaultsIfNeeded(churchId) {
  const settingsRef = db.collection(`churches/${churchId}/settings`).doc('config');
  const settingsDoc = await settingsRef.get();
  
  if (!settingsDoc.exists) {
    await settingsRef.set(DEFAULT_SETTINGS);
  }

  // Check and seed services if empty
  const svcRef = db.collection(`churches/${churchId}/services`);
  const svcSnap = await svcRef.get();
  if (svcSnap.empty) {
    for (const svc of DEFAULT_SERVICES) {
      await svcRef.doc(svc.id).set(svc);
    }
  }

  // Check and seed income categories if empty
  const icRef = db.collection(`churches/${churchId}/income_categories`);
  const icSnap = await icRef.get();
  if (icSnap.empty) {
    for (const ic of DEFAULT_INCOME_CATEGORIES) {
      await icRef.doc(ic.id).set(ic);
    }
  }

  // Check and seed expense categories if empty
  const ecRef = db.collection(`churches/${churchId}/expense_categories`);
  const ecSnap = await ecRef.get();
  if (ecSnap.empty) {
    for (const ec of DEFAULT_EXPENSE_CATEGORIES) {
      await ecRef.doc(ec.id).set(ec);
    }
  }
}

// GET all settings
exports.getSettings = async (req, res) => {
  try {
    const churchId = getChurchId(req);
    await seedDefaultsIfNeeded(churchId);
    
    const settingsDoc = await db.collection(`churches/${churchId}/settings`).doc('config').get();
    
    const [servicesSnap, icSnap, ecSnap] = await Promise.all([
      db.collection(`churches/${churchId}/services`).get(),
      db.collection(`churches/${churchId}/income_categories`).get(),
      db.collection(`churches/${churchId}/expense_categories`).get()
    ]);
    
    res.json({
      settings: settingsDoc.exists ? { ...DEFAULT_SETTINGS, ...settingsDoc.data() } : DEFAULT_SETTINGS,
      services: servicesSnap.docs.map(d => ({ id: d.id, ...d.data() })),
      income_categories: icSnap.docs.map(d => ({ id: d.id, ...d.data() })),
      expense_categories: ecSnap.docs.map(d => ({ id: d.id, ...d.data() }))
    });
  } catch (e) {
    console.error(e);
    res.status(500).json({ error: 'Failed to load settings' });
  }
};

// UPDATE a settings section (e.g. church_profile, financial, etc.)
exports.updateSettings = async (req, res) => {
  try {
    const churchId = getChurchId(req);
    const { section } = req.params;
    const updates = req.body;
    
    const settingsRef = db.collection(`churches/${churchId}/settings`).doc('config');
    const doc = await settingsRef.get();
    
    if (doc.exists) {
      const current = doc.data();
      current[section] = { ...(current[section] || {}), ...updates };
      await settingsRef.update(current);
      res.json({ message: 'Settings saved', settings: current[section] });
    } else {
      res.status(404).json({ error: 'Settings not found' });
    }
  } catch (e) {
    console.error(e);
    res.status(500).json({ error: 'Failed to save settings' });
  }
};

